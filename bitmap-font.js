function rasterText(text, scale = 1, gap = 0) {
  const size = Math.max(1, scale | 0);
  const space = Math.max(0, gap | 0);
  const chars = [...String(text)];
  const width = chars.reduce((total, _, index) => total + 5 * size + (index ? space : 0), 0) || size;
  const height = 7 * size;
  const pixels = new Uint8Array(width * height);
  let origin = 0;
  for (const char of chars) {
    const rows = FONT[char] || FONT['?'];
    for (let y = 0; y < 7; y++) {
      const bits = rows[y];
      for (let x = 0; x < 5; x++) {
        if (((bits >> (4 - x)) & 1) === 0) continue;
        for (let dy = 0; dy < size; dy++) {
          const row = (y * size + dy) * width;
          for (let dx = 0; dx < size; dx++) pixels[row + origin + x * size + dx] = 1;
        }
      }
    }
    origin += 5 * size + space;
  }
  return {width, height, pixels};
}

