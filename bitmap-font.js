// 5×7 printer-style bitmap. Every mark is a full pixel. Nothing here is a curve.
function g(rows) {
  return rows.map(row => {
    let bits = 0;
    for (const cell of row) bits = (bits << 1) | (cell === '#' ? 1 : 0);
    return bits;
  });
}
